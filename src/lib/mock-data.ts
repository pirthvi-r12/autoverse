const showcasePhoto = (folder: string) => `/images/${folder}/01.jpg`;

function oneImage(carId: string, folder: string, label: string) {
  return [
    {
      id: `img-${folder}`,
      car_id: carId,
      url: showcasePhoto(folder),
      alt_text: label,
      sort_order: 0,
      is_cover: true,
    },
  ];
}

function car(
  partial: Omit<Car, "slug" | "features" | "is_featured" | "created_at"> & {
    features?: string[];
    is_featured?: boolean;
  }
): Car {
  const slug = buildCarSlug(
    partial.brand,
    partial.model,
    partial.year,
    partial.id.slice(0, 8)
  );
  return {
    ...partial,
    slug,
    features: partial.features ?? [],
    is_featured: partial.is_featured ?? false,
    created_at: new Date().toISOString(),
    images: partial.images ?? [],
  };
}

